// Rasterises Natural Earth 110m land (world-atlas devDependency) into a 2-degree bitmask.
// Output is committed so the app has zero runtime map dependencies and zero tile requests.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);
const polys = [];
for (const f of land.features ?? [land]) {
  const g = f.geometry;
  (g.type === 'Polygon' ? [g.coordinates] : g.coordinates).forEach((p) => polys.push(p));
}
const inRing = (x, y, ring) => {
  let c = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
const inPoly = (x, y, p) => inRing(x, y, p[0]) && !p.slice(1).some((h) => inRing(x, y, h));
const W = 180, H = 80; // 2deg cells, lat 84N..76S
const bits = [];
for (let r = 0; r < H; r++) {
  let row = '';
  for (let c = 0; c < W; c++) {
    const lon = -180 + c * 2 + 1, lat = 84 - r * 2 - 1;
    row += polys.some((p) => inPoly(lon, lat, p)) ? '1' : '0';
  }
  bits.push(row);
}
const hex = bits.map((row) => row.replace(/(.{4})/g, (m) => parseInt(m, 2).toString(16)));
writeFileSync('src/engine/landmask.ts',
  `// GENERATED by scripts/gen-landmask.mjs - 2deg land grid, lat 84N..76S, lon -180..180\nexport const LAND_W = ${W};\nexport const LAND_H = ${H};\nexport const LAND_TOP_LAT = 84;\nexport const LAND_ROWS: string[] = ${JSON.stringify(hex)};\n`);
console.log('land cells:', bits.join('').split('1').length - 1);
